export function getFlashBackPostBySlug(slug) {
  return flashBackPosts.find((post) => post.slug === slug) ?? null
}

export function getFlashBackAdjacent(slug) {
  const index = flashBackPosts.findIndex((post) => post.slug === slug)
  if (index < 0) return { prev: null, next: null }
  return {
    prev: index > 0 ? flashBackPosts[index - 1] : null,
    next: index < flashBackPosts.length - 1 ? flashBackPosts[index + 1] : null,
  }
}

export function getFlashBackRelated(slug, limit = 3) {
  return flashBackPosts.filter((post) => post.slug !== slug).slice(0, limit)
}
