export function getRemembrancePostBySlug(slug) {
  return remembrancePosts.find((post) => post.slug === slug) ?? null
}

export function getRemembranceAdjacent(slug) {
  const index = remembrancePosts.findIndex((post) => post.slug === slug)
  if (index < 0) return { prev: null, next: null }
  return {
    prev: index > 0 ? remembrancePosts[index - 1] : null,
    next: index < remembrancePosts.length - 1 ? remembrancePosts[index + 1] : null,
  }
}

export function getRemembranceRelated(slug, limit = 4) {
  return remembrancePosts.filter((post) => post.slug !== slug).slice(0, limit)
}
