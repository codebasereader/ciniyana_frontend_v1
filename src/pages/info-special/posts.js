export function getInfoSpecialAdjacent(slug) {
  const index = infoSpecialPosts.findIndex((post) => post.slug === slug)
  if (index < 0) return { prev: null, next: null }
  return {
    prev: index > 0 ? infoSpecialPosts[index - 1] : null,
    next: index < infoSpecialPosts.length - 1 ? infoSpecialPosts[index + 1] : null,
  }
}

export function getInfoSpecialRelated(slug, limit = 4) {
  return infoSpecialPosts.filter((post) => post.slug !== slug).slice(0, limit)
}
